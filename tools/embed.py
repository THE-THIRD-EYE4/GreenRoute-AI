#!/usr/bin/env python3
"""Embed web/index.html into the ESP32 firmware as web_index.h.

Run from anywhere after editing the dashboard:
    python tools/embed.py          # gzip-compressed (default, ~4x smaller)
    python tools/embed.py --raw    # plain text, handy for debugging

Writes firmware/EV_Tracker_v4_WebDash/web_index.h. Do not edit that file by hand.
Standard library only.
"""
import argparse
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "firmware" / "EV_Tracker_v4_WebDash" / "web_index.h"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", action="store_true", help="store uncompressed instead of gzip")
    args = ap.parse_args()

    html = SRC.read_bytes()
    data = html if args.raw else gzip.compress(html, compresslevel=9, mtime=0)

    lines = []
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")

    OUT.write_text(
        "// GENERATED by tools/embed.py from web/index.html - do not edit by hand.\n"
        f"// Source {len(html)} bytes, stored {len(data)} bytes ({'raw' if args.raw else 'gzip'}).\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        f"#define WEB_INDEX_GZIP {0 if args.raw else 1}\n"
        f"const size_t WEB_INDEX_LEN = {len(data)};\n"
        "const uint8_t WEB_INDEX[] PROGMEM = {\n"
        + "\n".join(lines)
        + "\n};\n",
        encoding="ascii",
    )
    print(f"{SRC.relative_to(ROOT)} ({len(html)} B) -> {OUT.relative_to(ROOT)} ({len(data)} B, {'raw' if args.raw else 'gzip'})")


if __name__ == "__main__":
    main()
